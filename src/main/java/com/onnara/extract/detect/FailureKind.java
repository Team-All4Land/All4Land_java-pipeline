package com.onnara.extract.detect;

/**
 * 판별·추출이 실패한 <b>이유의 갈래</b> — 실패 건을 사후에 분류·재처리하기 위한 축이다.
 *
 * <p>전량 배치에서 나오는 수백 건의 실패는 파일 하나하나의 예외 메시지로는 다룰 수 없다.
 * "구버전이라 못 읽는다"(변환하면 살릴 수 있다)와 "암호가 걸렸다"(원본 소유자에게 받아야 한다),
 * "파일이 깨졌다"(포기)는 대응이 전혀 다른데, 지금은 셋이 한 덩어리로 세어진다.
 */
public enum FailureKind {

    /** 한글 3.0 이하 구버전(.hwp) — CFB가 아니라 hwplib이 읽지 못한다. 변환하면 살릴 수 있다. */
    HWP3_LEGACY("한글 3.0 이하 구버전 파일 — hwplib이 읽지 못합니다(한글에서 재저장 필요)"),

    /** 확장자는 .hwp인데 OLE 복합문서(CFB)가 아니다 — 개명된 다른 형식이거나 헤더 손상. */
    NOT_COMPOUND_FILE("HWP 컨테이너(OLE 복합문서)가 아닙니다 — 다른 형식을 .hwp로 개명했거나 헤더가 손상됐습니다"),

    /** 암호·배포용 문서 — 열쇠 없이는 본문에 접근할 수 없다. */
    ENCRYPTED("암호가 걸려 있습니다(배포용 문서 포함) — 암호 해제본이 필요합니다"),

    /** 확장자는 .hwpx인데 ZIP이 아니다 — .hwp를 .hwpx로 개명한 파일이 흔하다. */
    NOT_ZIP("HWPX 컨테이너(ZIP)가 아닙니다 — .hwp를 .hwpx로 개명했을 수 있습니다"),

    /** ZIP 구조가 깨졌거나 항목을 풀 수 없다. */
    ZIP_CORRUPT("ZIP 구조가 손상돼 항목을 읽을 수 없습니다"),

    /** 본문 XML이 규격에 맞지 않는다(HWPX section*.xml, HML 본문). */
    XML_PARSE("본문 XML을 파싱할 수 없습니다"),

    /**
     * 컨테이너는 정상인데 그 안의 문서 구조를 읽다 깨졌다 — 라이브러리가 감당하지 못하는
     * 레코드이거나 실제 손상이다. 컨테이너 자체가 잘못된 갈래와 구분해야 대응이 갈린다.
     */
    DOCUMENT_PARSE("컨테이너는 정상이나 내부 문서 구조를 읽지 못했습니다(손상 또는 라이브러리 미지원 레코드)"),

    /** PDF를 열지 못했다 — xref 손상, %PDF 헤더 없음 등. */
    PDF_LOAD("PDF를 열 수 없습니다(구조 손상 또는 PDF가 아님)"),

    /** 0바이트 파일. */
    EMPTY_FILE("빈 파일(0바이트)입니다"),

    /** 읽을 파일이 없다 — 경로가 사라졌거나 권한이 없다. */
    FILE_ACCESS("파일을 읽을 수 없습니다(경로 없음 또는 권한 부족)"),

    /** 판별기가 등록되지 않은 확장자. */
    UNSUPPORTED_EXT("지원하지 않는 확장자입니다"),

    /** 메모리 부족 — 파일 하나가 힙을 다 먹었다. 힙을 늘리거나 해당 파일을 제외해야 한다. */
    OUT_OF_MEMORY("메모리가 부족합니다 — JVM 힙(-Xmx)을 늘리거나 해당 파일을 제외하세요"),

    /** 위 어디에도 들어맞지 않는 입출력 오류. */
    IO("입출력 오류입니다"),

    /** 분류하지 못한 나머지 — 이 갈래가 늘어나면 분류 규칙을 보강해야 한다는 신호다. */
    OTHER("분류되지 않은 오류입니다");

    /** 사람이 읽을 한 줄 설명 — 집계 출력에 그대로 쓴다. */
    private final String description;

    /** 설명을 지정해 갈래를 만든다. */
    FailureKind(String description) {
        this.description = description;
    }

    /** 사람이 읽을 한 줄 설명. */
    public String description() {
        return description;
    }
}
