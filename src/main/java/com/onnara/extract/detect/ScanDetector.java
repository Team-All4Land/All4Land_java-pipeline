package com.onnara.extract.detect;

import java.nio.file.Path;

/**
 * 1차 분기: 스캔본 판별 계약.
 *
 * <p>판정 규칙은 네 형식 공통으로 한 줄이다:
 *
 * <pre>
 * 스캔본 = 네이티브 본문 텍스트가 한 글자도 없다 AND 임베디드 이미지가 1개 이상
 * </pre>
 *
 * <p>적용 범위만 형식별로 다르다. HWP/HWPX/HML은 문서 흐름 모델이라 페이지가 렌더링 시점에
 * 결정되므로 <b>문서 전체</b>를 집계하고, PDF는 페이지가 물리적 단위여서 <b>첫 페이지</b>에만
 * 적용한다({@link PdfScanDetector}).
 *
 * <p><b>이미지의 개수·크기·면적은 판정 근거가 아니다.</b> 사진이 지면 대부분을 차지한다는
 * 것만으로는 스캔본이 아니다 — 고시류에는 붙임 현장사진·위치도처럼 본문이 사진으로 채워진
 * 네이티브 문서가 흔하다. 이미지 유무는 "OCR로 얻을 게 있는가"를 확인하는 전제 조건일 뿐이다
 * (이미지가 없으면 빈 문서이지 스캔본이 아니다).
 *
 * <p>지면 점유율도 신호가 되지 않는다. 본문 전체가 이미지 한 장인 문서와 붙임 사진이 여러 장
 * 들어간 문서를 실측하면 둘 다 <b>본문 폭의 96~100%, 인쇄 영역의 약 40%</b>로 구분되지 않는다.
 * 기하 조건을 추가하면 판별력은 안 늘고 오판 경로만 는다.
 *
 * <p>스캔본으로 판별되면 이미지가 유일한 본문 출처로 취급돼 OCR 서브프로세스로 라우팅되고,
 * OCR 실패는 해당 파일의 [실패]가 된다.
 */
public interface ScanDetector {

    /**
     * 본문 텍스트가 이 글자 수 이상이면 네이티브 문서로 확정하는 공통 임계치 — 한 글자다.
     *
     * <p>임계치가 한 글자라는 것은 판별의 부담이 전부 <b>"본문 텍스트를 빠짐없이, 그리고
     * 본문만 세는가"</b>로 옮겨간다는 뜻이다. 컨테이너 하나를 빠뜨리면 사진 문서가 스캔본으로,
     * 머리말·꼬리말을 본문으로 세면 진짜 스캔본이 네이티브로 뒤집힌다. 구현체는 표 셀·글상자·
     * 캡션까지 세되 머리말·꼬리말·각주는 세지 않아야 한다.
     *
     * <p>PDF는 이 중 뒤쪽 요구를 지킬 수 없다 — {@code PDFTextStripper}가 페이지 텍스트를
     * 평면화해 머리말·꼬리말을 구조적으로 분리할 방법이 없다. {@link PdfScanDetector}에 적어 둔
     * 대가다.
     */
    int MIN_TEXT_CHARS = 1;

    /** 파일이 스캔본(본문이 이미지 안에만 있는 문서)인지 판정한다. */
    boolean isScanned(Path file);
}
